enum PulseFieldPresentation {
    case standard
    case today
}

enum PulseAmbientMotionPolicy {
    static func allowsMotion(
        requested: Bool,
        reduceMotion: Bool,
        sceneIsActive: Bool
    ) -> Bool {
        requested && !reduceMotion && sceneIsActive
    }
}

struct PulseFieldBackground: View {
    var presentation: PulseFieldPresentation = .standard
    var allowsMotion = true

    @Environment(\.horizontalSizeClass) private var horizontalSizeClass
    @Environment(\.pulseVisualTheme) private var visualTheme
    @Environment(\.accessibilityReduceMotion) private var reduceMotion
    @Environment(\.scenePhase) private var scenePhase

    @ViewBuilder
    var body: some View {
        switch visualTheme {
        case .sunlitDay:
            sunlitField
        case .editorialJournal:
            editorialField
        case .quietField:
            quietField
        case .moonTide:
            moonTideField
        case .prismLedger:
            prismLedgerField
        }
    }

    private var moonTideField: some View {
        TimelineView(.animation(
            minimumInterval: PulseDesign.ambientFieldMinimumInterval,
            paused: !allowsAmbientMotion
        )) { timeline in
            GeometryReader { proxy in
                let phase = ambientPhase(at: timeline.date)
                PulseMoonTideFieldCanvas(
                    size: proxy.size,
                    phase: phase,
                    showsPrism: presentation == .today
                )
            }
        }
        .ignoresSafeArea()
        .allowsHitTesting(false)
        .accessibilityHidden(true)
    }

    private var prismLedgerField: some View {
        TimelineView(.animation(
            minimumInterval: PulseDesign.ambientFieldMinimumInterval,
            paused: !allowsAmbientMotion
        )) { timeline in
            GeometryReader { proxy in
                let phase = ambientPhase(at: timeline.date)
                PulsePrismLedgerFieldCanvas(
                    size: proxy.size,
                    phase: phase,
                    showsGrid: presentation == .today
                )
            }
        }
        .ignoresSafeArea()
        .allowsHitTesting(false)
        .accessibilityHidden(true)
    }

    private var quietField: some View {
        TimelineView(.animation(
            minimumInterval: PulseDesign.ambientFieldMinimumInterval,
            paused: !allowsAmbientMotion
        )) { timeline in
            GeometryReader { proxy in
                let phase = ambientPhase(at: timeline.date)
                let counterPhase = ambientPhase(
                    at: timeline.date.addingTimeInterval(PulseDesign.ambientFieldCycleDuration * 0.37)
                )

                PulseQuietFieldCanvas(
                    size: proxy.size,
                    phase: phase,
                    counterPhase: counterPhase,
                    showsPlayfulLayer: presentation == .today,
                    usesRegularWidthGeometry: horizontalSizeClass == .regular
                )
            }
        }
        .ignoresSafeArea()
        .allowsHitTesting(false)
        .accessibilityHidden(true)
    }

    private var sunlitField: some View {
        TimelineView(.animation(
            minimumInterval: PulseDesign.ambientFieldMinimumInterval,
            paused: !allowsAmbientMotion
        )) { timeline in
            GeometryReader { proxy in
                let phase = ambientPhase(at: timeline.date)
                let counterPhase = ambientPhase(
                    at: timeline.date.addingTimeInterval(
                        PulseDesign.ambientFieldCycleDuration * 0.41
                    )
                )

                PulseSunlitFieldCanvas(
                    size: proxy.size,
                    phase: phase,
                    counterPhase: counterPhase,
                    presentation: presentation
                )
            }
        }
        .ignoresSafeArea()
        .allowsHitTesting(false)
        .accessibilityHidden(true)
    }

    private var editorialField: some View {
        TimelineView(.animation(
            minimumInterval: PulseDesign.ambientFieldMinimumInterval,
            paused: !allowsAmbientMotion
        )) { timeline in
            GeometryReader { proxy in
                let phase = ambientPhase(at: timeline.date)
                let counterPhase = ambientPhase(
                    at: timeline.date.addingTimeInterval(
                        PulseDesign.ambientFieldCycleDuration
                            * PulseDesign.editorialAmbientCounterPhaseOffset
                    )
                )

                PulseEditorialFieldCanvas(
                    size: proxy.size,
                    phase: phase,
                    counterPhase: counterPhase
                )
            }
        }
        .ignoresSafeArea()
        .allowsHitTesting(false)
        .accessibilityHidden(true)
    }

    private var allowsAmbientMotion: Bool {
        PulseAmbientMotionPolicy.allowsMotion(
            requested: allowsMotion,
            reduceMotion: reduceMotion,
            sceneIsActive: scenePhase == .active
        )
    }

    private func ambientPhase(at date: Date) -> Double {
        guard allowsAmbientMotion else { return 0 }
        let progress = date.timeIntervalSinceReferenceDate
            .truncatingRemainder(dividingBy: PulseDesign.ambientFieldCycleDuration)
            / PulseDesign.ambientFieldCycleDuration
        return progress * 2 * .pi
    }
}

private struct PulseMoonTideFieldCanvas: View {
    let size: CGSize
    let phase: Double
    let showsPrism: Bool

    var body: some View {
        ZStack {
            Image("PulseMoonTideBackground")
                .resizable()
                .scaledToFill()
                .frame(width: size.width, height: size.height)
                .offset(y: CGFloat(sin(phase)) * 3)
                .clipped()

            PulseDesign.moonCanvas.opacity(showsPrism ? 0.18 : 0.38)
        }
        .frame(width: size.width, height: size.height)
        .clipped()
    }
}

private struct PulsePrismLedgerFieldCanvas: View {
    let size: CGSize
    let phase: Double
    let showsGrid: Bool

    var body: some View {
        ZStack {
            PulseDesign.prismCanvas

            if showsGrid {
                Canvas { context, canvas in
                    let step = max(56, min(canvas.width, canvas.height) * 0.12)
                    var x: CGFloat = 0
                    while x <= canvas.width {
                        var line = Path()
                        line.move(to: CGPoint(x: x, y: 0))
                        line.addLine(to: CGPoint(x: x, y: canvas.height))
                        context.stroke(
                            line,
                            with: .color(PulseDesign.prismDivider.opacity(0.24)),
                            lineWidth: PulseDesign.thinLineWidth
                        )
                        x += step
                    }

                    var y: CGFloat = 0
                    while y <= canvas.height {
                        var line = Path()
                        line.move(to: CGPoint(x: 0, y: y))
                        line.addLine(to: CGPoint(x: canvas.width, y: y))
                        context.stroke(
                            line,
                            with: .color(PulseDesign.prismDivider.opacity(0.24)),
                            lineWidth: PulseDesign.thinLineWidth
                        )
                        y += step
                    }
                }
            }

            RoundedRectangle(cornerRadius: 36, style: .continuous)
                .fill(PulseDesign.prismCanvasDeep.opacity(0.62))
                .frame(width: size.width * 0.32, height: size.height * 1.18)
                .rotationEffect(.degrees(-18 + sin(phase) * 0.35))
                .offset(x: size.width * 0.24, y: -size.height * 0.12)

            RoundedRectangle(cornerRadius: 36, style: .continuous)
                .fill(PulseDesign.prismAccent.opacity(0.18))
                .frame(width: size.width * 0.24, height: size.height * 0.88)
                .rotationEffect(.degrees(58 + cos(phase) * 0.30))
                .offset(x: size.width * 0.28, y: size.height * 0.10)

            RoundedRectangle(cornerRadius: 28, style: .continuous)
                .fill(PulseDesign.prismCoral.opacity(0.20))
                .frame(width: size.width * 0.20, height: size.height * 0.42)
                .rotationEffect(.degrees(-12))
                .offset(x: size.width * 0.42, y: size.height * 0.24)
        }
        .frame(width: size.width, height: size.height)
        .clipped()
    }
}

