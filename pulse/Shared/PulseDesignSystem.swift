import Foundation
import SwiftUI

struct PulseVisualThemeEnvironmentKey: EnvironmentKey {
    /// Uninjected trees must show the free theme, never a paid skin.
    static let defaultValue = PulseVisualThemeAccessPolicy.freeTheme
}

extension EnvironmentValues {
    var pulseVisualTheme: PulseVisualTheme {
        get { self[PulseVisualThemeEnvironmentKey.self] }
        set { self[PulseVisualThemeEnvironmentKey.self] = newValue }
    }
}

/// One paper and one ink. Every theme is the same page; only these change.
struct PulseThemePalette {
    let paper: Color
    let paperRaised: Color
    let ink: Color
    let muted: Color
    let rule: Color
    let seal: Color
    let onSeal: Color
    let sealWash: Color

    fileprivate init(assetPrefix prefix: String) {
        paper = Color("\(prefix)Paper")
        paperRaised = Color("\(prefix)PaperRaised")
        ink = Color("\(prefix)Ink")
        muted = Color("\(prefix)Muted")
        rule = Color("\(prefix)Rule")
        seal = Color("\(prefix)Seal")
        onSeal = Color("\(prefix)OnSeal")
        sealWash = Color("\(prefix)SealWash")
    }
}

