/// Chrome floats on glass where the system draws glass, and on material before it.
private struct PulseGlassModifier<GlassShape: Shape>: ViewModifier {
    let shape: GlassShape
    let isInteractive: Bool
    @Environment(\.pulseVisualTheme) private var visualTheme

    func body(content: Content) -> some View {
        if #available(iOS 26.0, *) {
            content.glassEffect(isInteractive ? .regular.interactive() : .regular, in: shape)
        } else {
            content
                .background(.regularMaterial, in: shape)
                .overlay {
                    shape.stroke(PulseDesign.appDivider(for: visualTheme), lineWidth: PulseDesign.thinLineWidth)
                }
        }
    }
}

extension View {
    func pulseGlass<GlassShape: Shape>(in shape: GlassShape, interactive: Bool = false) -> some View {
        modifier(PulseGlassModifier(shape: shape, isInteractive: interactive))
    }
}

/// Today and History share one bar: nothing but the way to settings, so the page keeps its own title.
private struct PulsePrimaryToolbarModifier: ViewModifier {
    let source: PulsePrimarySection
    @Environment(\.pulseVisualTheme) private var visualTheme

    func body(content: Content) -> some View {
        content
            .navigationBarTitleDisplayMode(.inline)
            .toolbar {
                ToolbarItem(placement: .topBarTrailing) {
                    NavigationLink(value: PulseNavigationDestination.settings) {
                        Image(systemName: "gearshape")
                            .foregroundStyle(PulseDesign.appInk(for: visualTheme))
                    }
                    .tint(PulseDesign.appInk(for: visualTheme))
                    .accessibilityLabel("settings.navigation_title")
                    .accessibilityIdentifier("settings.navigation.open.\(source.rawValue)")
                }
            }
    }
}

extension View {
    func pulsePrimaryToolbar(source: PulsePrimarySection) -> some View {
        modifier(PulsePrimaryToolbarModifier(source: source))
    }
}

/// A bar pinned under scrolling content. The page's paper fades in behind it, so rows that
/// scroll underneath never show through the button.
private struct PulseBottomBarModifier<Bar: View>: ViewModifier {
    let bar: Bar
    @Environment(\.pulseVisualTheme) private var visualTheme

    func body(content: Content) -> some View {
        let paper = PulseDesign.appChromeBackground(for: visualTheme)
        content.safeAreaInset(edge: .bottom, spacing: 0) {
            bar.background(alignment: .top) {
                // A fixed fade, then solid paper; the keyboard's safe area is left alone so the
                // fade stays attached to the bar when the keyboard is up.
                VStack(spacing: 0) {
                    LinearGradient(colors: [paper.opacity(0), paper], startPoint: .top, endPoint: .bottom)
                        .frame(height: PulseDesign.spacing24)
                    paper
                }
                .ignoresSafeArea(.container, edges: .bottom)
            }
        }
    }
}

private struct PulseSoftScrollEdgesModifier: ViewModifier {
    func body(content: Content) -> some View {
        if #available(iOS 26.0, *) {
            content.scrollEdgeEffectStyle(.soft, for: .all)
        } else {
            content
        }
    }
}

extension View {
    func pulseBottomBar<Bar: View>(@ViewBuilder _ bar: () -> Bar) -> some View {
        modifier(PulseBottomBarModifier(bar: bar()))
    }

    func pulseSoftScrollEdges() -> some View {
        modifier(PulseSoftScrollEdgesModifier())
    }
}

struct PulseSecondaryNavigationBackButton: View {
    @Environment(\.dismiss) private var dismiss
    @Environment(\.pulseVisualTheme) private var visualTheme

    var body: some View {
        Button {
            dismiss()
        } label: {
            Label {
                Text("navigation.back")
            } icon: {
                Image(systemName: "chevron.backward")
            }
            .foregroundStyle(PulseDesign.appInk(for: visualTheme))
        }
        .accessibilityIdentifier("navigation.back")
    }
}

private struct PulseSecondaryNavigationModifier: ViewModifier {
    let isEnabled: Bool

    func body(content: Content) -> some View {
        content
            .navigationBarBackButtonHidden(isEnabled)
            .toolbar {
                if isEnabled {
                    ToolbarItem(placement: .topBarLeading) {
                        PulseSecondaryNavigationBackButton()
                    }
                }
            }
    }
}

extension View {
    func pulseSecondaryNavigation(isEnabled: Bool = true) -> some View {
        modifier(PulseSecondaryNavigationModifier(isEnabled: isEnabled))
    }

    func pulseFormRows(for theme: PulseVisualTheme) -> some View {
        listRowBackground(PulseDesign.appSurface(for: theme))
            .listRowSeparatorTint(PulseDesign.appDivider(for: theme))
    }
}
